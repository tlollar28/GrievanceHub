export function templateDisplayName(templateId: string): string {
  if (templateId === OFFICIAL_STEP_1_TEMPLATE_ID) {
    return 'Official Grievance Worksheet — Step 1'
  }
  if (templateId === OFFICIAL_STEP_2_TEMPLATE_ID) {
    return 'Official Standard Grievance Form — Step 2'
  }
  return templateId
}

export function stepTypeLabel(stepType: string | null | undefined): string {
  if (stepType === 'step_1_initial') return 'Step 1 — Initial'
  if (stepType === 'step_2_appeal') return 'Step 2 — Appeal'
  return stepType ?? 'Unknown step'
}
